//! Regenerate `src/gcode_params.rs`, the client's built-in G-Code parameter
//! table.
//!
//! The table is checked in rather than rebuilt at client-build time because
//! `klippy-client` installs on machines that have no host source to scan. Run
//! this when a host command's declared parameter names change:
//!
//! ```console
//! cargo run -p klippy-client --bin gen-gcode-params
//! cargo fmt --all
//! ```
//!
//! The formatter step matters: this generator writes one command per line while
//! the repository keeps `cargo fmt`'s multi-line shape, so skipping it leaves a
//! whole-file diff. A stale table does not wait for a test either —
//! `build.rs` re-scans in a checkout and fails the build when the checked-in
//! table disagrees with the host source.
//!
//! It scans `src/core/klippy`, prints every registration it could not resolve,
//! and writes `BUILTIN` next to the crate's library. The freshness test in
//! `tests/gcode_params_table.rs` fails when the checked-in table and a fresh
//! scan disagree.

use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use klippy_client::gcode_params_scan;

fn main() -> Result<(), Box<dyn Error>> {
    let scan = gcode_params_scan::scan()?;

    for site in &scan.unresolved {
        println!("unresolved: {}:{} — {}", site.file, site.line, site.reason);
    }
    println!(
        "{} registration call sites: {} resolved, {} unresolved; {} commands, {} parameter entries",
        scan.call_sites,
        scan.resolved_call_sites,
        scan.unresolved.len(),
        scan.commands.len(),
        scan.commands.iter().map(|c| c.params.len()).sum::<usize>(),
    );

    let out = render(&scan.commands);
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/gcode_params.rs");
    fs::write(&path, out)?;
    println!("wrote {}", path.display());
    Ok(())
}

/// Render `BUILTIN` as Rust source.
///
/// One command per line, so a change to parameter names shows as a one-line
/// diff.
fn render(commands: &[gcode_params_scan::Command]) -> String {
    let mut out = String::from(
        "// @generated by `cargo run -p klippy-client --bin gen-gcode-params`; do not edit.\n\
         \n\
         /// The parameter names each G-Code command declares, for a client that\n\
         /// cannot reach a host's `status.gcode.commands[<name>][\"parameters\"]`.\n\
         ///\n\
         /// Merged from every registration of a command, in first-seen order,\n\
         /// sorted by command name. `tests/gcode_params_table.rs` keeps it\n\
         /// equal to a fresh scan of `src/core/klippy`.\n\
         pub const BUILTIN: &[(&str, &[&str])] = &[\n",
    );
    for command in commands {
        let mut line = format!("    ({:?}, &[", command.name);
        for (i, param) in command.params.iter().enumerate() {
            if i > 0 {
                line.push_str(", ");
            }
            let _ = write!(line, "{param:?}");
        }
        line.push_str("]),\n");
        out.push_str(&line);
    }
    out.push_str("];\n");
    out
}
