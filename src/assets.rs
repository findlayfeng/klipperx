//! Release the embedded config and documentation assets to disk.
//!
//! Moonraker reads a Klipper installation from disk: the `config/` examples a
//! frontend's config helper offers, and the `docs/` tree its documentation
//! lookup serves. This host is a single binary with no installation layout, so
//! the trees are embedded at build time (build.rs, `assets_tree.rs`) and
//! released to a real directory at start-up, before anything serves the API.
//!
//! The released root is `<base>/assets-<fnv64>/`, where the hash is the
//! build-time fingerprint of the embedded file set: a rebuilt binary releases
//! under a new name, and a root that is already complete is reused with zero
//! writes. `<base>` comes from a three-level chain — `RUNTIME_DIRECTORY`, then
//! `$XDG_RUNTIME_DIR/klipperx`, then `/tmp/klipperx-<uid>` — and a location
//! that was *configured* but is not writable is an error, never a silent
//! fallback: the release path is what `/printer/info` reports as
//! `klipper_path`, and Moonraker must find what it was told.

use std::fmt;
use std::fs;
use std::io;
use std::os::unix::fs::PermissionsExt as _;
use std::path::{Component, Path, PathBuf};
use std::time::{Duration, SystemTime};

// The embedded file table and its fingerprint: `pub static ASSET_FILES` and
// `pub const ASSETS_FNV64`, generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/assets_tree.rs"));

/// How long a stale release or staging directory must sit untouched before
/// garbage collection removes it.
///
/// An hour is far longer than any publish takes; it only exists so a crash
/// cannot delete a directory another process — an older binary still running —
/// is serving from.
const GC_MAX_AGE: Duration = Duration::from_secs(60 * 60);

/// Release the embedded assets and return the released root.
///
/// The environment lookup is the real environment; tests inject their own
/// ([`release_with`]) because setting variables around parallel tests races.
///
/// # Errors
/// [`ReleaseError`] — a configured location that is unusable, or an I/O failure
/// while publishing. An unusable configured location is an error, not a
/// fallback: see the module doc.
pub fn release() -> Result<PathBuf, ReleaseError> {
    release_with(|key| std::env::var(key).ok())
}

/// [`release`] with an injected environment lookup.
///
/// A key "is configured" when the lookup returns a non-empty string; an empty
/// string counts as unset and falls through the chain.
pub fn release_with(lookup: impl Fn(&str) -> Option<String>) -> Result<PathBuf, ReleaseError> {
    let base = resolve_base_with(lookup)?;
    let root = base.join(format!("assets-{ASSETS_FNV64}"));
    if valid(&root) {
        return Ok(root);
    }

    // Publish through a staging directory: the root either does not exist or
    // is incomplete, and a half-written root must never be what `valid` finds.
    let tmp = base.join(format!(".assets-tmp-{}", std::process::id()));
    let _ = fs::remove_dir_all(&tmp); // a crash may have left this pid's behind
    write_tree(&tmp)?;
    match fs::rename(&tmp, &root) {
        Ok(()) => {}
        // `rename` onto an existing non-empty directory fails with ENOTEMPTY
        // (and some platforms spell the race EEXIST); both mean "the name is
        // taken", which the validity check below then judges.
        Err(err)
            if err.raw_os_error() == Some(libc::ENOTEMPTY)
                || err.raw_os_error() == Some(libc::EEXIST) =>
        {
            if valid(&root) {
                // A concurrent release of the same version won the rename;
                // its root is complete, so ours is dropped as a duplicate.
                let _ = fs::remove_dir_all(&tmp);
            } else {
                // An incomplete root (a crash between the checks, or an edit
                // by hand): heal it by replacing it, once.
                if let Err(err) = fs::remove_dir_all(&root) {
                    let _ = fs::remove_dir_all(&tmp);
                    return Err(ReleaseError::Io {
                        context: format!("cannot replace the incomplete {}", root.display()),
                        source: err,
                    });
                }
                if let Err(err) = fs::rename(&tmp, &root) {
                    let _ = fs::remove_dir_all(&tmp);
                    return Err(ReleaseError::Io {
                        context: format!("cannot publish {} after replacing it", root.display()),
                        source: err,
                    });
                }
            }
        }
        Err(err) => {
            let _ = fs::remove_dir_all(&tmp);
            return Err(ReleaseError::Io {
                context: format!("cannot publish {}", root.display()),
                source: err,
            });
        }
    }

    gc(&base);
    Ok(root)
}

/// Resolve the base directory the assets are released under.
///
/// The chain, first hit wins; a configured-but-unusable level is an error, not
/// a step down:
///
/// 1. `RUNTIME_DIRECTORY` (systemd's per-service runtime dir): its first
///    `:`-separated segment — a unit may pass several paths — must be absolute
///    and writable.
/// 2. `$XDG_RUNTIME_DIR/klipperx`, created if needed, must be writable.
/// 3. `/tmp/klipperx-<uid>`, created if needed, must be writable.
pub fn resolve_base_with(lookup: impl Fn(&str) -> Option<String>) -> Result<PathBuf, ReleaseError> {
    if let Some(value) = lookup("RUNTIME_DIRECTORY").filter(|value| !value.is_empty()) {
        // A unit file may list several paths; only the first is usable here.
        let first = value.split(':').next().unwrap_or(&value).to_string();
        let path = PathBuf::from(&first);
        if !path.is_absolute() {
            return Err(ReleaseError::ConfiguredInvalid {
                var: "RUNTIME_DIRECTORY".to_string(),
                path: first,
            });
        }
        ensure_writable("RUNTIME_DIRECTORY", &path, CreateDir::Single)?;
        return Ok(path);
    }
    if let Some(runtime) = lookup("XDG_RUNTIME_DIR").filter(|value| !value.is_empty()) {
        let path = PathBuf::from(runtime).join("klipperx");
        ensure_writable("XDG_RUNTIME_DIR", &path, CreateDir::Recursive)?;
        return Ok(path);
    }
    // No environment at all: the hardcoded fallback, named as such in errors.
    let path = PathBuf::from(format!("/tmp/klipperx-{}", effective_uid()));
    ensure_writable("hardcoded /tmp fallback", &path, CreateDir::Recursive)?;
    Ok(path)
}

/// Which way [`ensure_writable`] creates the directory.
enum CreateDir {
    /// `create_dir` — the configured root itself must not be conjured from a
    /// chain of missing parents.
    Single,
    /// `create_dir_all` — the fallback chains one name onto a directory that
    /// may itself be missing.
    Recursive,
}

/// Make sure `dir` exists and this process can write into it.
///
/// The check is a probe file, not the permission bits: only an actual write
/// says the directory is usable (a read-only mount, an ACL, a foreign uid).
fn ensure_writable(var: &str, dir: &Path, create: CreateDir) -> Result<(), ReleaseError> {
    let unwritable = |source: io::Error| ReleaseError::ConfiguredUnwritable {
        var: var.to_string(),
        path: dir.display().to_string(),
        source,
    };
    if !dir.exists() {
        let created = match create {
            CreateDir::Single => fs::create_dir(dir).or_else(|err| {
                if err.kind() == io::ErrorKind::AlreadyExists {
                    Ok(())
                } else {
                    Err(err)
                }
            }),
            CreateDir::Recursive => fs::create_dir_all(dir),
        };
        created.map_err(unwritable)?;
    }
    let probe = dir.join(format!(".probe-{}", std::process::id()));
    fs::write(&probe, b"").map_err(unwritable)?;
    fs::remove_file(&probe).map_err(unwritable)?;
    Ok(())
}

/// Whether `root` is a complete release: the layout every consumer may rely on.
fn valid(root: &Path) -> bool {
    root.join("config").is_dir()
        && root.join("docs").is_dir()
        && root.join("docs/klipper").is_dir()
        && root.join("docs").join("README.md").exists()
}

/// Write every embedded file into the staging directory `tmp`.
///
/// Modes are set explicitly, not left to umask: Moonraker may run as another
/// uid and must be able to read what this process wrote.
fn write_tree(tmp: &Path) -> Result<(), ReleaseError> {
    fs::create_dir(tmp).map_err(|source| ReleaseError::Io {
        context: format!("cannot create the staging directory {}", tmp.display()),
        source,
    })?;
    set_dir_mode(tmp)?;
    for (relative, data) in ASSET_FILES {
        assert_safe(relative);
        let path = tmp.join(relative);
        let parent = path.parent().expect("an asset path has a parent");
        fs::create_dir_all(parent).map_err(|source| ReleaseError::Io {
            context: format!("cannot create {}", parent.display()),
            source,
        })?;
        set_dir_mode(parent)?;
        fs::write(&path, data).map_err(|source| ReleaseError::Io {
            context: format!("cannot write {}", path.display()),
            source,
        })?;
        fs::set_permissions(&path, fs::Permissions::from_mode(0o644)).map_err(|source| {
            ReleaseError::Io {
                context: format!("cannot make {} world-readable", path.display()),
                source,
            }
        })?;
    }
    Ok(())
}

/// Set the directory mode explicitly (0755), ignoring the umask.
fn set_dir_mode(dir: &Path) -> Result<(), ReleaseError> {
    fs::set_permissions(dir, fs::Permissions::from_mode(0o755)).map_err(|source| ReleaseError::Io {
        context: format!("cannot make {} traversable", dir.display()),
        source,
    })
}

/// The embedded list is build-generated, so its paths are safe by
/// construction; this asserts that rather than trusting it.
fn assert_safe(relative: &str) {
    for component in Path::new(relative).components() {
        if !matches!(component, Component::Normal(_)) {
            panic!("embedded asset path escapes the release root: {relative}");
        }
    }
}

/// Remove stale release and staging directories next to the current one.
///
/// Best-effort and never fatal: the release succeeded, and a failed cleanup
/// only costs disk. An hour of age separates "left behind" from "another
/// process may still be serving from it".
fn gc(base: &Path) {
    let Ok(entries) = fs::read_dir(base) else {
        return;
    };
    let current = format!("assets-{ASSETS_FNV64}");
    let cutoff = SystemTime::now() - GC_MAX_AGE;
    for entry in entries.filter_map(|entry| entry.ok()) {
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let stale = entry
            .metadata()
            .and_then(|metadata| metadata.modified())
            .is_ok_and(|modified| modified < cutoff);
        if !stale {
            continue;
        }
        let removable =
            (name.starts_with("assets-") && name != current) || name.starts_with(".assets-tmp-");
        if removable {
            let _ = fs::remove_dir_all(entry.path());
        }
    }
}

/// The effective user id the fallback path is scoped by.
fn effective_uid() -> u32 {
    // SAFETY: `geteuid` takes no arguments and cannot fail.
    unsafe { libc::geteuid() }
}

/// Everything that can go wrong releasing the assets. Each variant names the
/// environment variable and path involved, so a report says which level of the
/// chain failed and why (errno included).
#[derive(Debug)]
pub enum ReleaseError {
    /// A configured base that is not an absolute path.
    ConfiguredInvalid {
        /// The variable the value came from.
        var: String,
        /// The value that was given.
        path: String,
    },
    /// A configured base that cannot be written to. Not a fallback: the
    /// release path is reported to clients, so a silent move would make the
    /// report a lie.
    ConfiguredUnwritable {
        /// The variable the value came from.
        var: String,
        /// The directory that is not usable.
        path: String,
        /// The failed operation's errno.
        source: io::Error,
    },
    /// An I/O failure while publishing the release.
    Io {
        /// What operation failed, naming the path.
        context: String,
        /// The failed operation's errno.
        source: io::Error,
    },
}

impl fmt::Display for ReleaseError {
    fn fmt(&self, out: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ReleaseError::ConfiguredInvalid { var, path } => {
                write!(out, "printer assets: {var}={path} is not an absolute path")
            }
            ReleaseError::ConfiguredUnwritable { var, path, source } => {
                write!(out, "printer assets: {var}={path} is not usable: {source}")
            }
            ReleaseError::Io { context, source } => {
                write!(out, "printer assets: {context}: {source}")
            }
        }
    }
}

impl std::error::Error for ReleaseError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            ReleaseError::ConfiguredInvalid { .. } => None,
            ReleaseError::ConfiguredUnwritable { source, .. } => Some(source),
            ReleaseError::Io { source, .. } => Some(source),
        }
    }
}

