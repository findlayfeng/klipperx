#[cfg(test)]
mod tests {
    use super::*;

    /// A scratch directory under `/tmp`, unique to one test.
    fn scratch(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "klipperx-assets-test-{}-{name}",
            std::process::id()
        ));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).expect("the scratch directory can be created");
        dir
    }

    /// Release into `base` as a configured `RUNTIME_DIRECTORY` would.
    fn release_into(base: &Path) -> Result<PathBuf, ReleaseError> {
        let base = base.display().to_string();
        release_with(move |key| (key == "RUNTIME_DIRECTORY").then(|| base.clone()))
    }

    /// The names directly inside `dir`, sorted.
    fn entries(dir: &Path) -> Vec<String> {
        let mut names: Vec<String> = fs::read_dir(dir)
            .expect("the directory can be listed")
            .map(|entry| {
                entry
                    .expect("an entry")
                    .file_name()
                    .to_string_lossy()
                    .into_owned()
            })
            .collect();
        names.sort();
        names
    }

    #[test]
    fn test_a_configured_runtime_directory_is_the_base() {
        let base = scratch("resolve-configured");
        let wanted = base.display().to_string();

        let resolved =
            resolve_base_with(|key| (key == "RUNTIME_DIRECTORY").then(|| wanted.clone()))
                .expect("a configured absolute path resolves");

        assert_eq!(resolved, base);
    }

    #[test]
    fn test_a_multi_value_runtime_directory_is_used_first_segment_first() {
        let base = scratch("resolve-first-segment");
        let value = format!("{}:/somewhere/else", base.display());

        let resolved = resolve_base_with(|key| (key == "RUNTIME_DIRECTORY").then(|| value.clone()))
            .expect("the first segment of a multi-value path resolves");

        assert_eq!(resolved, base);
    }

    #[test]
    fn test_without_runtime_directory_the_xdg_base_is_used() {
        let base = scratch("resolve-xdg");

        let resolved = resolve_base_with(|key| match key {
            "XDG_RUNTIME_DIR" => Some(base.display().to_string()),
            _ => None,
        })
        .expect("XDG resolves");

        assert_eq!(resolved, base.join("klipperx"));
        assert!(resolved.is_dir(), "the XDG base is created");
    }

    #[test]
    fn test_without_any_variable_the_hardcoded_tmp_base_is_used() {
        let resolved = resolve_base_with(|_| None).expect("the fallback resolves");

        assert_eq!(
            resolved,
            PathBuf::from(format!("/tmp/klipperx-{}", effective_uid()))
        );
    }

    #[test]
    fn test_an_empty_value_counts_as_unconfigured() {
        let base = scratch("resolve-empty");

        let resolved = resolve_base_with(|key| match key {
            "RUNTIME_DIRECTORY" => Some(String::new()),
            "XDG_RUNTIME_DIR" => Some(base.display().to_string()),
            _ => None,
        })
        .expect("the empty value falls through to XDG");

        assert_eq!(resolved, base.join("klipperx"));
    }

    #[test]
    fn test_a_relative_runtime_directory_is_an_invalid_configuration() {
        let error = resolve_base_with(|key| {
            (key == "RUNTIME_DIRECTORY").then(|| "relative/dir".to_string())
        })
        .expect_err("a relative configured path is an error");

        let message = error.to_string();
        assert!(message.contains("RUNTIME_DIRECTORY"), "{message}");
        assert!(message.contains("relative/dir"), "{message}");
        assert!(matches!(error, ReleaseError::ConfiguredInvalid { .. }));
    }

    #[test]
    fn test_an_unwritable_configured_base_is_an_error_not_a_fallback() {
        // As root the chmod below would not make anything unwritable, so the
        // assertion would be vacuous; skip the case instead of passing it.
        if effective_uid() == 0 {
            return;
        }
        let base = scratch("resolve-unwritable");
        fs::set_permissions(&base, fs::Permissions::from_mode(0o555)).expect("chmod works");

        let error = resolve_base_with(|key| {
            (key == "RUNTIME_DIRECTORY").then(|| base.display().to_string())
        })
        .expect_err("an unwritable configured base is an error, not a fallback");

        let message = error.to_string();
        assert!(message.contains("RUNTIME_DIRECTORY"), "{message}");
        assert!(message.contains("Permission denied"), "{message}");

        fs::set_permissions(&base, fs::Permissions::from_mode(0o755)).expect("chmod back");
    }

    #[test]
    fn test_release_fills_the_config_and_docs_trees() {
        let base = scratch("release-e2e");

        let root = release_into(&base).expect("the release succeeds");

        assert_eq!(root, base.join(format!("assets-{ASSETS_FNV64}")));
        assert!(valid(&root));
        assert!(
            !entries(&root.join("config")).is_empty(),
            "config/ is filled"
        );
        assert!(
            !entries(&root.join("docs").join("klipper")).is_empty(),
            "docs/klipper/ is filled"
        );
        assert!(root.join("docs").join("config.md").is_file());

        // The generated index: the upstream docs are pointed at, all six
        // manuals are listed, and the source README's prose is not embedded.
        let index = fs::read_to_string(root.join("docs").join("README.md")).expect("readable");
        assert!(index.contains("klipper/"), "{index}");
        for manual in [
            "client.md",
            "config.md",
            "firmware-build.md",
            "gcode-commands.md",
            "logging.md",
            "mcu-connection.md",
        ] {
            assert!(index.contains(manual), "index misses {manual}:\n{index}");
        }
        assert!(
            !index.contains("面向最终用户"),
            "the source README leaked in"
        );
        assert!(!index.contains("文档首页"), "the source README leaked in");
    }

    #[test]
    fn test_release_is_idempotent() {
        let base = scratch("release-idempotent");

        let first = release_into(&base).expect("the first release succeeds");
        let second = release_into(&base).expect("the second release succeeds");

        assert_eq!(first, second);
        let leftovers: Vec<String> = entries(&base)
            .into_iter()
            .filter(|name| name.starts_with(".assets-tmp-"))
            .collect();
        assert!(leftovers.is_empty(), "staging leftovers: {leftovers:?}");
    }

    #[test]
    fn test_release_adopts_a_complete_concurrent_tree() {
        let base = scratch("release-adopt");
        let root = base.join(format!("assets-{ASSETS_FNV64}"));
        fs::create_dir_all(root.join("config")).expect("pre-create config");
        fs::create_dir_all(root.join("docs").join("klipper")).expect("pre-create docs/klipper");
        fs::write(root.join("docs").join("README.md"), "complete").expect("pre-create the index");

        let released = release_into(&base).expect("a complete tree is adopted");

        assert_eq!(released, root);
        assert!(valid(&root));
    }

    #[test]
    fn test_release_heals_an_incomplete_tree() {
        let base = scratch("release-heal");
        let root = base.join(format!("assets-{ASSETS_FNV64}"));
        fs::create_dir_all(&root).expect("pre-create an empty root");

        let released = release_into(&base).expect("an incomplete tree is healed");

        assert_eq!(released, root);
        assert!(valid(&root));
        assert!(
            !entries(&root.join("config")).is_empty(),
            "the healed tree is complete"
        );
    }

    #[test]
    fn test_gc_removes_only_stale_trees() {
        let base = scratch("release-gc");
        let old = base.join("assets-deadbeef");
        let fresh = base.join("assets-1234567890abcdef");
        fs::create_dir_all(&old).expect("the old tree exists");
        fs::create_dir_all(&fresh).expect("the fresh tree exists");
        let age = SystemTime::now() - GC_MAX_AGE - Duration::from_secs(60);
        let handle = fs::File::open(&old).expect("the old tree can be opened");
        handle.set_modified(age).expect("the old tree can be aged");

        let released = release_into(&base).expect("the release succeeds");

        assert!(!old.exists(), "the stale tree was collected");
        assert!(fresh.exists(), "the fresh tree was kept");
        assert!(released.exists(), "the current tree was kept");
    }
}
