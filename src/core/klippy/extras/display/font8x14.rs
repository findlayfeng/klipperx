#[cfg(test)]
mod tests {
    use super::*;

    /// The bytes of one upstream `b'…'` literal: the font uses `\xNN` escapes
    /// and plain ASCII, nothing else (`font8x14.py:19-275`).
    fn literal_bytes(literal: &str) -> Vec<u8> {
        let mut bytes = Vec::new();
        let mut chars = literal.chars();
        while let Some(ch) = chars.next() {
            if ch != '\\' {
                bytes.push(ch as u8);
                continue;
            }
            match chars.next() {
                Some('x') => {
                    let high = chars.next().expect("two hex digits").to_digit(16);
                    let low = chars.next().expect("two hex digits").to_digit(16);
                    bytes.push((high.unwrap() * 16 + low.unwrap()) as u8);
                }
                other => panic!("unexpected escape {other:?}"),
            }
        }
        bytes
    }

    /// Upstream's table, read from its own source, or `None` when the
    /// submodule is not checked out.
    fn upstream_font() -> Option<Vec<Vec<u8>>> {
        let path = klipperx_test_support::klipper_dir().join("klippy/extras/display/font8x14.py");
        let text = std::fs::read_to_string(&path).ok()?;
        let body = text.split("VGA_FONT = [").nth(1)?.split(']').next()?;
        let mut rows = Vec::new();
        for line in body.lines() {
            let Some(rest) = line.trim().strip_prefix("b'") else {
                continue;
            };
            let literal = rest.trim_end().trim_end_matches(',').trim_end_matches('\'');
            rows.push(literal_bytes(literal));
        }
        Some(rows)
    }

    #[test]
    fn test_the_vendored_font_has_not_drifted() {
        // A copy needs a guard that says so, the way the shipped `display.cfg`
        // has one: a worktree without the submodule has nothing to compare
        // against and skips — point `KLIPPERX_KLIPPER_DIR` at the main checkout
        // to run it.
        let Some(upstream) = upstream_font() else {
            return;
        };
        assert_eq!(upstream.len(), 256, "upstream VGA_FONT changed shape");
        for (code, row) in upstream.iter().enumerate() {
            assert_eq!(
                VGA_FONT[code].to_vec(),
                *row,
                "glyph 0x{code:02x} differs from font8x14.py"
            );
        }
    }

    #[test]
    fn test_the_shapes_are_sixteen_bytes_and_the_degrees_glyph_is_where_st7920_reads_it() {
        // `st7920` draws `degrees` from entry `0xf8` (`st7920.py:17`).
        assert_eq!(VGA_FONT.len(), 256);
        assert_eq!(VGA_FONT[0xf8][2..6], [0x38, 0x6c, 0x6c, 0x38]);
        // The space is blank, which is what a page's blank framebuffer matches.
        assert_eq!(VGA_FONT[b' ' as usize], [0u8; 16]);
    }
}
